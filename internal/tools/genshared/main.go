// Command genshared writes .gen/go/shared: aliases of every exported type
// and enum constant in the api package, under Cadence's import path.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	if len(os.Args) != 3 {
		log.Fatal("usage: genshared <api dir> <output file>")
	}
	src, err := generate(filepath.Clean(os.Args[1]))
	if err != nil {
		log.Fatal(err)
	}
	// The output path comes from the Makefile, not from untrusted input.
	if err := os.WriteFile(filepath.Clean(os.Args[2]), src, 0o600); err != nil { // #nosec G703 -- build tool argument
		log.Fatal(err)
	}
}

func generate(dir string) ([]byte, error) {
	fset := token.NewFileSet()
	files, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return nil, err
	}
	var types, consts []string
	for _, f := range files {
		if strings.HasSuffix(f, "_test.go") {
			continue
		}
		file, err := parser.ParseFile(fset, f, nil, 0)
		if err != nil {
			return nil, err
		}
		for _, decl := range file.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok {
				continue
			}
			for _, spec := range gd.Specs {
				switch s := spec.(type) {
				case *ast.TypeSpec:
					if s.Name.IsExported() {
						types = append(types, s.Name.Name)
					}
				case *ast.ValueSpec:
					if gd.Tok != token.CONST {
						continue
					}
					for _, n := range s.Names {
						if n.IsExported() && s.Type != nil {
							consts = append(consts, n.Name)
						}
					}
				}
			}
		}
	}
	sort.Strings(types)
	sort.Strings(consts)

	var b bytes.Buffer
	b.WriteString(`// Code generated by internal/tools/genshared. DO NOT EDIT.

// Package shared mirrors go.uber.org/cadence/.gen/go/shared with aliases of
// the takt wire types, so type switches on service errors and references to
// shared types keep compiling after migration. Field types differ from
// Cadence's Thrift structs: takt uses plain values instead of pointers.
package shared

import "github.com/larsla/takt/api"

type (
`)
	for _, t := range types {
		fmt.Fprintf(&b, "\t%s = api.%s\n", t, t)
	}
	b.WriteString(")\n\nconst (\n")
	for _, c := range consts {
		fmt.Fprintf(&b, "\t%s = api.%s\n", c, c)
	}
	b.WriteString("\n\t// Cadence's names for close statuses.\n")
	for _, v := range []string{"Completed", "Failed", "Canceled", "Terminated", "ContinuedAsNew", "TimedOut"} {
		fmt.Fprintf(&b, "\tWorkflowExecutionCloseStatus%s = api.CloseStatus%s\n", v, v)
	}
	b.WriteString(")\n")
	return format.Source(b.Bytes())
}

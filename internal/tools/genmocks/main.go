// Command genmocks writes the mocks package: testify mocks of the client
// interfaces in the style of mockery, as go.uber.org/cadence/mocks has.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"go/types"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"golang.org/x/tools/go/packages"
)

const sdkPath = "github.com/larsla/takt/internal/sdk"

// mocked lists the interfaces to mock and the mock type names.
var mocked = []struct{ iface, name string }{
	{"Client", "Client"},
	{"DomainClient", "DomainClient"},
	{"WorkflowRun", "WorkflowRun"},
	{"HistoryEventIterator", "HistoryEventIterator"},
	{"Value", "Value"},
}

func main() {
	if len(os.Args) != 2 {
		log.Fatal("usage: genmocks <output dir>")
	}
	pkgs, err := packages.Load(&packages.Config{Mode: packages.NeedTypes | packages.NeedName | packages.NeedImports | packages.NeedDeps}, sdkPath)
	if err != nil || len(pkgs) != 1 || len(pkgs[0].Errors) > 0 {
		log.Fatalf("load %s: %v %v", sdkPath, err, pkgs)
	}
	scope := pkgs[0].Types.Scope()
	for _, m := range mocked {
		obj := scope.Lookup(m.iface)
		if obj == nil {
			log.Fatalf("%s not found", m.iface)
		}
		iface, ok := obj.Type().Underlying().(*types.Interface)
		if !ok {
			log.Fatalf("%s is not an interface", m.iface)
		}
		src, err := generate(m.name, iface)
		if err != nil {
			log.Fatal(err)
		}
		out := filepath.Join(filepath.Clean(os.Args[1]), m.name+".go")
		// The output path comes from the Makefile, not from untrusted input.
		if err := os.WriteFile(out, src, 0o600); err != nil { // #nosec G703 -- build tool argument
			log.Fatal(err)
		}
	}
}

type gen struct {
	b       bytes.Buffer
	imports map[string]string // path -> name
}

func (g *gen) qual(p *types.Package) string {
	name := p.Name()
	g.imports[p.Path()] = name
	return name
}

func (g *gen) typ(t types.Type) string { return types.TypeString(t, g.qual) }

func generate(name string, iface *types.Interface) ([]byte, error) {
	g := &gen{imports: map[string]string{"github.com/stretchr/testify/mock": "mock"}}
	var methods []*types.Func
	for i := range iface.NumMethods() {
		methods = append(methods, iface.Method(i))
	}
	sort.Slice(methods, func(i, j int) bool { return methods[i].Name() < methods[j].Name() })
	var body bytes.Buffer
	fmt.Fprintf(&body, "// %s is a mock of the %s interface.\ntype %s struct {\n\tmock.Mock\n}\n", name, name, name)
	for _, m := range methods {
		g.method(&body, name, m)
	}
	fmt.Fprintf(&body, `
// New%s creates a %s mock that asserts its expectations when the test
// ends.
func New%s(t interface {
	mock.TestingT
	Cleanup(func())
}) *%s {
	m := &%s{}
	m.Mock.Test(t)
	t.Cleanup(func() { m.AssertExpectations(t) })
	return m
}
`, name, name, name, name, name)

	var paths []string
	for p := range g.imports {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	g.b.WriteString("// Code generated by internal/tools/genmocks. DO NOT EDIT.\n\n")
	g.b.WriteString("package mocks\n\nimport (\n")
	for _, p := range paths {
		fmt.Fprintf(&g.b, "\t%s %q\n", g.imports[p], p)
	}
	g.b.WriteString(")\n\n")
	g.b.Write(body.Bytes())
	return format.Source(g.b.Bytes())
}

func (g *gen) method(w *bytes.Buffer, recv string, m *types.Func) {
	sig := m.Type().(*types.Signature)
	params, results := sig.Params(), sig.Results()
	var decl, names, types_ []string
	for i := range params.Len() {
		p := params.At(i)
		n := p.Name()
		if n == "" || n == "_" {
			n = fmt.Sprintf("_a%d", i)
		}
		t := g.typ(p.Type())
		if sig.Variadic() && i == params.Len()-1 {
			t = "..." + g.typ(p.Type().(*types.Slice).Elem())
		}
		decl = append(decl, n+" "+t)
		names = append(names, n)
		types_ = append(types_, t)
	}
	var rtypes []string
	for i := range results.Len() {
		rtypes = append(rtypes, g.typ(results.At(i).Type()))
	}
	rlist := strings.Join(rtypes, ", ")
	if len(rtypes) > 1 {
		rlist = "(" + rlist + ")"
	}
	fmt.Fprintf(w, "\n// %s mocks %s.%s.\nfunc (_m *%s) %s(%s) %s {\n", m.Name(), recv, m.Name(), recv, m.Name(), strings.Join(decl, ", "), rlist)

	// The arguments as Called sees them: variadic ones spread out.
	callArgs := strings.Join(names, ", ")
	if sig.Variadic() {
		fixed := names[:len(names)-1]
		fmt.Fprintf(w, "\tvar _ca []interface{}\n")
		if len(fixed) > 0 {
			fmt.Fprintf(w, "\t_ca = append(_ca, %s)\n", strings.Join(fixed, ", "))
		}
		v := names[len(names)-1]
		fmt.Fprintf(w, "\tfor _, _va := range %s {\n\t\t_ca = append(_ca, _va)\n\t}\n", v)
		callArgs = "_ca..."
		names[len(names)-1] = v + "..."
	}
	if len(rtypes) == 0 {
		fmt.Fprintf(w, "\t_m.Called(%s)\n}\n", callArgs)
		return
	}
	fmt.Fprintf(w, "\tret := _m.Called(%s)\n\n\tif len(ret) == 0 {\n\t\tpanic(\"no return value specified for %s\")\n\t}\n\n", callArgs, m.Name())
	ftype := "func(" + strings.Join(types_, ", ") + ")"
	call := strings.Join(names, ", ")
	for i, rt := range rtypes {
		fmt.Fprintf(w, "\tvar r%d %s\n", i, rt)
	}
	if len(rtypes) > 1 {
		fmt.Fprintf(w, "\tif rf, ok := ret.Get(0).(%s %s); ok {\n\t\treturn rf(%s)\n\t}\n", ftype, rlist, call)
	}
	for i, rt := range rtypes {
		fmt.Fprintf(w, "\tif rf, ok := ret.Get(%d).(%s %s); ok {\n\t\tr%d = rf(%s)\n\t} else", i, ftype, rt, i, call)
		switch {
		case rt == "error":
			fmt.Fprintf(w, " {\n\t\tr%d = ret.Error(%d)\n\t}\n", i, i)
		case nillable(results.At(i).Type()):
			fmt.Fprintf(w, " if ret.Get(%d) != nil {\n\t\tr%d = ret.Get(%d).(%s)\n\t}\n", i, i, i, rt)
		default:
			fmt.Fprintf(w, " {\n\t\tr%d = ret.Get(%d).(%s)\n\t}\n", i, i, rt)
		}
	}
	var rs []string
	for i := range rtypes {
		rs = append(rs, fmt.Sprintf("r%d", i))
	}
	fmt.Fprintf(w, "\n\treturn %s\n}\n", strings.Join(rs, ", "))
}

func nillable(t types.Type) bool {
	switch t.Underlying().(type) {
	case *types.Pointer, *types.Interface, *types.Slice, *types.Map, *types.Signature, *types.Chan:
		return true
	}
	return false
}

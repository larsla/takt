// Command gengetters writes nil-safe Get<Field> and IsSet<Field> methods
// for the structs of the api package, named the way Cadence's Thrift
// structs name them (WorkflowID becomes GetWorkflowId), so code that reads
// shared types through getters keeps compiling.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

func main() {
	if len(os.Args) != 3 {
		log.Fatal("usage: gengetters <api dir> <output file>")
	}
	src, err := generate(filepath.Clean(os.Args[1]), filepath.Base(os.Args[2]))
	if err != nil {
		log.Fatal(err)
	}
	// The output path comes from the Makefile, not from untrusted input.
	if err := os.WriteFile(filepath.Clean(os.Args[2]), src, 0o600); err != nil { // #nosec G703 -- build tool argument
		log.Fatal(err)
	}
}

// idRe matches "ID" as a word inside a Go name: before an upper-case
// letter, an "s" or the end.
var idRe = regexp.MustCompile(`ID([A-Zs]|$)`)

// thriftName is the name Cadence's Thrift code gives a takt field.
func thriftName(field string) string { return idRe.ReplaceAllString(field, "Id$1") }

// typos are Cadence getter names that don't follow from the field name.
var typos = map[string]string{
	"PendingChildExecutionInfo.WorkflowTypeName": "WorkflowTypName",
}

// getterNames returns the names to generate getters under: Cadence's
// Thrift name, and the takt name too where Cadence keeps "ID" in some
// structs (PendingActivityInfo.GetActivityID).
func getterNames(structName, field string) []string {
	names := []string{thriftName(field)}
	if field != names[0] {
		names = append(names, field)
	}
	if t, ok := typos[structName+"."+field]; ok {
		names = append(names, t)
	}
	return names
}

type field struct {
	name, typ string
	kind      string // "ptr", "slice", "map", "bool", "string", "number", "struct", "other"
}

func generate(dir, out string) ([]byte, error) {
	fset := token.NewFileSet()
	files, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return nil, err
	}
	structs := map[string][]field{}
	methods := map[string]bool{}
	named := map[string]string{} // named non-struct types and their underlying kind
	for _, f := range files {
		if strings.HasSuffix(f, "_test.go") || filepath.Base(f) == out {
			continue
		}
		file, err := parser.ParseFile(fset, f, nil, 0)
		if err != nil {
			return nil, err
		}
		for _, decl := range file.Decls {
			switch d := decl.(type) {
			case *ast.FuncDecl:
				if d.Recv != nil && len(d.Recv.List) == 1 {
					methods[recvName(d.Recv.List[0].Type)+"."+d.Name.Name] = true
				}
			case *ast.GenDecl:
				for _, spec := range d.Specs {
					ts, ok := spec.(*ast.TypeSpec)
					if !ok || !ts.Name.IsExported() {
						continue
					}
					st, ok := ts.Type.(*ast.StructType)
					if !ok {
						named[ts.Name.Name] = kindOf(ts.Type, nil)
						continue
					}
					var fs []field
					for _, fl := range st.Fields.List {
						var tb bytes.Buffer
						if err := printer.Fprint(&tb, fset, fl.Type); err != nil {
							return nil, err
						}
						for _, n := range fl.Names {
							if n.IsExported() {
								fs = append(fs, field{name: n.Name, typ: tb.String(), kind: kindOf(fl.Type, nil)})
							}
						}
					}
					structs[ts.Name.Name] = fs
				}
			}
		}
	}
	names := make([]string, 0, len(structs))
	for n := range structs {
		names = append(names, n)
	}
	sort.Strings(names)

	var b bytes.Buffer
	b.WriteString("// Code generated by internal/tools/gengetters. DO NOT EDIT.\n\npackage api\n")
	// Cadence's Thrift enums have String methods; takt's are strings.
	var enums []string
	for n, k := range named {
		if k == "string" && !methods[n+".String"] {
			enums = append(enums, n)
		}
	}
	sort.Strings(enums)
	for _, n := range enums {
		fmt.Fprintf(&b, "\n// String returns v as a string.\nfunc (v %s) String() string { return string(v) }\n", n)
	}
	// Cadence's Thrift enums have Ptr methods too.
	for _, n := range enums {
		if !methods[n+".Ptr"] {
			fmt.Fprintf(&b, "\n// Ptr returns a pointer to v.\nfunc (v %s) Ptr() *%s { return &v }\n", n, n)
		}
	}
	for _, s := range names {
		for _, f := range structs[s] {
			kind := f.kind
			if k, ok := named[f.typ]; ok {
				kind = k
			}
			if kind == "struct" {
				// A plain struct value has no useful zero check.
				kind = "other"
			}
			for _, tn := range getterNames(s, f.name) {
				if get := "Get" + tn; !methods[s+"."+get] {
					fmt.Fprintf(&b, "\n// %s returns v.%s, or its zero value when v is nil.\nfunc (v *%s) %s() (o %s) {\n\tif v != nil {\n\t\to = v.%s\n\t}\n\treturn\n}\n",
						get, f.name, s, get, f.typ, f.name)
				}
				is := "IsSet" + tn
				if methods[s+"."+is] {
					continue
				}
				check := "v != nil"
				if nz := nonZero("v."+f.name, kind); nz != "" {
					check += " && " + nz
				}
				fmt.Fprintf(&b, "\n// %s reports whether v.%s is set to a non-zero value.\nfunc (v *%s) %s() bool {\n\treturn %s\n}\n",
					is, f.name, s, is, check)
			}
		}
	}
	return format.Source(b.Bytes())
}

func recvName(e ast.Expr) string {
	if s, ok := e.(*ast.StarExpr); ok {
		e = s.X
	}
	if id, ok := e.(*ast.Ident); ok {
		return id.Name
	}
	return ""
}

func kindOf(e ast.Expr, _ map[string]string) string {
	switch t := e.(type) {
	case *ast.StarExpr, *ast.InterfaceType, *ast.FuncType, *ast.ChanType:
		return "ptr"
	case *ast.ArrayType:
		if t.Len == nil {
			return "slice"
		}
		return "other"
	case *ast.MapType:
		return "map"
	case *ast.StructType:
		return "struct"
	case *ast.Ident:
		switch t.Name {
		case "bool":
			return "bool"
		case "string":
			return "string"
		case "int", "int8", "int16", "int32", "int64", "uint", "uint8", "uint16", "uint32", "uint64", "float32", "float64":
			return "number"
		}
		return t.Name // a named type, resolved through named
	}
	return "other"
}

func nonZero(x, kind string) string {
	switch kind {
	case "ptr":
		return x + " != nil"
	case "slice", "map":
		return "len(" + x + ") > 0"
	case "bool":
		return x
	case "string":
		return x + ` != ""`
	case "number":
		return x + " != 0"
	}
	return ""
}
